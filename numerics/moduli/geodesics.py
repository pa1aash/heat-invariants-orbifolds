def quad_polygon(lam):
    """The quadrilateral Q of a quad.Lambert instance."""
    vs = lam.quad_vertices()             # V, -conj V, -V, conj V  (ccw)
    sides = lam.quad_sides()             # east, north, west, south
    # side i joins vertex i to vertex i+1: V -> -conj V is the north side, etc.
    order = [1, 2, 3, 0]                 # north, west, south, east
    refl = [reflection_from_circle(complex(sides[k][0]), float(sides[k][1])) for k in order]
    return Polygon([complex(v) for v in vs], refl)


def triangle_polygon(pqr):
    """The S3 triangle (numerics/geometry.py placement): A = 0, B on the positive
    real axis, C on the ray arg z = pi/p; sides AB, BC (arc), CA."""
    import os
    import sys
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    from geometry import Triangle
    T = Triangle(*pqr)
    A, B, C = complex(T.A), complex(T.B), complex(T.C)
    refl = [reflection_from_line_through_origin(1.0 + 0j),
            reflection_from_circle(complex(T.z0), float(T.rho)),
            reflection_from_line_through_origin(C / abs(C))]
    return Polygon([A, B, C], refl)
